function fmtKey(d) {
  return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
}
function todayKey() { return fmtKey(new Date()); }
function dateCN(key) {
  const [y, m, d] = key.split('-').map(Number);
  return `${y}年${m}月${d}日 · 星期${'日一二三四五六'[new Date(y, m - 1, d).getDay()]}`;
}
function relLabel(key) {
  if (key === todayKey()) return '今天';
  const d = new Date(); d.setDate(d.getDate() - 1);
  if (key === fmtKey(d)) return '昨天';
  return dateCN(key);
}
function nthSunday(y, month, n) {
  const first = new Date(y, month - 1, 1);
  return (7 - first.getDay()) % 7 + 1 + (n - 1) * 7;
}
function getFestival(key) {
  const [y, m, d] = key.split('-').map(Number);
  const md = `${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
  const lf = LUNAR_FEST[y];
  if (lf && lf[md]) return { name: lf[md], legal: LEGAL_SET.has(lf[md]) };
  if (SOLAR_FEST[md]) return { name: SOLAR_FEST[md][0], legal: !!SOLAR_FEST[md][1] };
  if (m === 5 && d === nthSunday(y, 5, 2)) return { name: '母亲节', legal: false };
  if (m === 6 && d === nthSunday(y, 6, 3)) return { name: '父亲节', legal: false };
  return null;
}
function getDayPlan(key) {
  const [y] = key.split('-').map(Number);
  const p = HOLIDAY_PLAN[y];
  if (!p) return null;
  const md = key.slice(5);
  if (p.restSet.has(md)) return { type: 'rest', label: '休' };
  if (p.work[md]) return { type: 'work', label: '班', name: p.work[md] };
  return null;
}

